"use strict";
const fs = require("fs"), path = require("path"), os = require("os"), assert = require("assert");
const mock = require("./ae_mock");
const root = path.resolve(__dirname, "..");
const temporary = fs.mkdtempSync(path.join(os.tmpdir(),"noir-cep-"));
const env = mock.install({temp:temporary,fonts:["TimesNewRomanPSMT","Inter-Bold"]});
global.$.fileName = path.join(root,"cep/host/bridge.jsx");
(0,eval)(fs.readFileSync(global.$.fileName,"utf8"));
let shown = 0;
const show = global.Window.prototype.show;
global.Window.prototype.show = () => shown++;
const first = JSON.parse(global.NOIR_CEP.load(root));
global.Window.prototype.show = show;
assert.strictEqual(shown,0,"HTML host must not open the old ScriptUI window");
assert.ok(first.full && first.nodes.length > 100);
assert.strictEqual(first.nodes[0].visible,true);
assert.ok(first.nodes.some(n=>n.scroll)); assert.ok(first.nodes.some(n=>n.tabs));
assert.ok(first.nodes.some(n=>n.type==="edittext" && n.multiline));
const tree = new Map(first.nodes.map(n=>[n.id,n]));
function request(data) {
 const result=JSON.parse(global.NOIR_CEP.request(JSON.stringify(data)));
 assert.ok(!result.error,result.error);
 for(const n of result.nodes) tree.set(n.id,n);
 return result;
}
const styleTab=first.nodes.find(n=>n.type==="button"&&n.text==="3 · Стиль");
request({action:"click",id:styleTab.id});
assert.ok(tree.get(styleTab.id).tabSelected);
const advanced=first.nodes.find(n=>n.type==="checkbox"&&n.text==="Дополнительные настройки");
request({action:"click",id:advanced.id,value:true});
assert.ok([...tree.values()].find(n=>n.type==="button"&&n.text==="SFX").visible);
assert.strictEqual(request({action:"poll"}).nodes.length,0,"Idle polling must transfer only changed controls");
const sample={schema:"noir-captions/1",language:"ru",segments:[{words:[{text:"Привет",start:1,end:2}]}]};
const json=path.join(temporary,"captions.json"); fs.writeFileSync(json,JSON.stringify(sample));
global.app.project.activeItem=new mock.CompItem({duration:10});
global.File.openDialog=()=>mock.File(json);
request({action:"click",id:first.nodes.find(n=>n.text==="Загрузить результат…").id});
const editor=[...tree.values()].find(n=>n.type==="edittext"&&n.multiline);
assert.strictEqual(editor.text,"Привет");
request({action:"set",id:editor.id,value:"Здравствуйте"});
assert.ok([...tree.values()].some(n=>n.text.indexOf("Текст изменён — обновите фразу")===0));
request({action:"click",id:first.nodes.find(n=>n.text==="Создать субтитры").id});
assert.ok(global.app.project.activeItem._l.some(l=>/ЗДРАВСТВУЙТЕ|Здравствуйте/.test(l.name)));
assert.ok(!global.app.project.activeItem._l.some(l=>String(l.comment).indexOf(global.NOIR.SFX_TAG)===0));
assert.ok(JSON.parse(global.NOIR_CEP.request('{"action":"click","id":"999999"}')).error);
const main = new mock.CompItem({name:"Main"}), preview = new mock.CompItem({name:"NOIR Preview · Main"}), used = new mock.CompItem({name:"NOIR · Галерея стилей"});
used.usedIn=[main]; global.app.project._items.push(main,preview,used);
preview.remove=()=>{global.app.project._items.splice(global.app.project._items.indexOf(preview),1);};
const cleanup=request({action:"removePreviews"});
assert.ok(cleanup.notice.indexOf(": 1.")>0);
assert.ok(global.app.project._items.includes(main) && global.app.project._items.includes(used));
assert.ok(!global.app.project._items.includes(preview));
for(const id of Object.keys(env.tasks)) global.app.cancelTask(id);
fs.rmSync(temporary,{recursive:true,force:true});
console.log("CEP bridge: hidden host, navigation, editor, generation, manual-only SFX and incremental polling passed");
